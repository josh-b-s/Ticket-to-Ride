"""ticket_service.py — destination ticket draw and keep logic."""
from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from game.classes.game import Game

from game.classes.destination_ticket import DestinationTicket
from game.classes.player import Player


class TicketService:
    def __init__(self, game: Game) -> None:
        self.game = game

    #  Deck setup 

    def build_destination_deck(self) -> None:
        """
        Generate and load destination tickets from the current board.

        Tickets are auto-generated by Board.generate_tickets using
        all-pairs shortest paths, so any board.json file automatically
        produces an appropriate ticket set with no hardcoded data.
        """
        tickets = self.game.board.generate_tickets()
        self.game.destination_deck.load(tickets)

    #  Draw / return 

    def draw(self, count: int = 3) -> list[DestinationTicket]:
        return self.game.destination_deck.draw(count)

    def keep_tickets(
        self,
        player: Player,
        chosen: list[DestinationTicket],
        drawn: list[DestinationTicket],
    ) -> tuple[bool, str]:
        if not chosen:
            return False, "You must keep at least 1 ticket."
        for ticket in chosen:
            player.destination_tickets.append(ticket)
        returned = [t for t in drawn if t not in chosen]
        self.game.destination_deck.return_to_bottom(returned)
        return True, "Tickets chosen."